from .theme import CSS, FILTER_JS, ICON_CHECK, ICON_SUN_MOON, ICON_X, LOGO, THEME_BOOT, THEME_TOGGLE

LogHref = Callable[[StepResult], "str | None"]
STATUS_ORDER = (StepStatus.PASS, StepStatus.WAIVED, StepStatus.FAIL, StepStatus.TIMEOUT, StepStatus.SKIPPED)


def _e(value: object) -> str:
    return escape(str(value), quote=True)


def _st(status: str) -> str:
    return f'<span class="st {_e(status)}">{_e(status)}</span>'


def _row_duration(row: dict) -> float:
    if row.get("duration_s") is not None:
        return row["duration_s"]
    return _iso_delta_s(row["started_at"], row["finished_at"])


def _plural(n: int, word: str) -> str:
    return f"{n} {word}" + ("" if n == 1 else "s")


# ────────────────────────────────────────────────────────────── page shell


def page(
    title: str,
    body: str,
    *,
    nav: Sequence[tuple[str, str, bool]] = (),
    live: bool = False,
    scripts: str = "",
    home: str | None = None,
    subtitle: str = "report",
) -> str:
    """Wrap a body in the full document: head, topbar, footer, scripts."""
    links = "".join(
        f'<a href="{_e(href)}"{" aria-current=page" if current else ""}>{_e(label)}</a>'
        for label, href, current in nav
    )
    brand_open = f'<a class="brand" href="{_e(home)}">' if home else '<span class="brand">'
    brand_close = "</a>" if home else "</span>"
    live_badge = '<span class="live" title="Reloads when a new run lands"><i></i>live</span>' if live else ""
    return f"""<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="generator" content="gauntlet {__version__}">
<title>{_e(title)}</title>
<script>{THEME_BOOT}</script>
<style>{CSS}</style>
</head>
<body>
<header class="topbar"><div class="topbar-in">
  {brand_open}{LOGO}GAUNTLET <small>{_e(subtitle)}</small>{brand_close}
  <nav class="nav" aria-label="Sections">{links}</nav>
  <span class="spacer"></span>
  {live_badge}
  <button class="icon-btn" id="themeToggle" type="button" aria-label="Toggle light or dark theme">{ICON_SUN_MOON}</button>
</div></header>
<main>
{body}
</main>
<footer class="footer"><span>generated by gauntlet {__version__}</span><span>every commit runs the gauntlet.</span></footer>
<script>{THEME_TOGGLE}{scripts}</script>
</body>
</html>
"""


# ────────────────────────────────────────────────────────────── run report


def run_body(record: RunRecord, log_href: LogHref, actions: str = "") -> str:
    """The full report for one run."""
    results = list(record.results.values())
    counts = {s: sum(1 for r in results if r.status == s) for s in StepStatus}
    errors = sum(len(r.errors) for r in results)
    waived = sum(1 for r in results for v in r.errors if v.waived)
    warnings = sum(len(r.warnings) for r in results)
    flaky = [r for r in results if r.flaky]
    attempts = sum(r.attempts for r in results)
    peak = max_parallelism(record)
    crit = run_critical_path(record)
    crit_s = sum(record.results[s].duration_s for s in crit if s in record.results)
    duration = run_duration_s(record)

    icon = ICON_CHECK if record.status == "PASS" else ICON_X
    commit = ""
    if record.git_commit:
        commit = f'<span>commit <b>{_e(record.git_commit[:10])}</b></span>'
        if record.git_branch:
            commit += f'<span>branch <b>{_e(record.git_branch)}</b></span>'

    hero = f"""
<section class="card hero v-{_e(record.status)}" aria-label="Run summary">
  <div class="hero-top">
    <div style="min-width:0">
      <div class="eyebrow">Flow</div>
      <h1>{_e(record.flow_name)}</h1>
    </div>
    <div class="verdict {_e(record.status)}" role="status">{icon}{_e(record.status)}</div>
  </div>
  <div class="meta">
    <span>run <b>{_e(record.run_id)}</b></span>
    <span>started <b>{_e(record.started_at.replace("T", " "))}</b></span>
    <span>finished <b>{_e(record.finished_at.replace("T", " "))}</b></span>
    {commit}
  </div>
  {actions}
</section>"""

    dist = "".join(
        f'<span class="bg-{s.value}" style="width:{100 * counts[s] / max(len(results), 1):.2f}%" '
        f'title="{counts[s]} {s.value}"></span>'
        for s in STATUS_ORDER
        if counts[s]
    )
    legend = "".join(
        f'<span><i class="bg-{s.value}"></i>{counts[s]} {s.value.lower()}</span>'
        for s in STATUS_ORDER
        if counts[s]
    )
    unwaived = errors - waived
    kpis = f"""
<section class="card card-b" aria-label="Key numbers">
  <div class="kpis">
    <div class="kpi"><div class="l">Duration</div><div class="n">{duration:.2f}<small>s</small></div><div class="d">wall clock</div></div>
    <div class="kpi"><div class="l">Steps</div><div class="n">{len(results)}</div><div class="d">{counts[StepStatus.PASS]} pass · {counts[StepStatus.WAIVED]} waived</div></div>
    <div class="kpi {'bad' if unwaived else ('warn' if waived else 'good')}"><div class="l">Errors</div><div class="n">{errors}</div><div class="d">{unwaived} unwaived · {waived} waived</div></div>
    <div class="kpi {'warn' if warnings else ''}"><div class="l">Warnings</div><div class="n">{warnings}</div><div class="d">never fail a step</div></div>
    <div class="kpi"><div class="l">Peak parallel</div><div class="n">{peak or '—'}</div><div class="d">steps running at once</div></div>
    <div class="kpi {'warn' if flaky else ''}"><div class="l">Flaky</div><div class="n">{len(flaky)}</div><div class="d">{attempts} attempt(s) total</div></div>
  </div>
  <div style="margin-top:16px"><div class="dist" role="img" aria-label="Status distribution">{dist}</div><div class="legend">{legend}</div></div>
</section>"""

    graph = dag_svg(record)
    crit_line = ""
    if len(crit) > 1:
        crit_line = (
            f'<span class="tag crit" title="The dependency chain that bounded wall-clock time">'
            f"critical path · {crit_s:.2f}s</span>"
        )
    graph_card = f"""
<section class="card" aria-labelledby="h-dag">
  <div class="card-h"><h2 id="h-dag">Flow graph</h2><span class="sub">{_plural(len(results), 'step')} · click a node for detail</span><span class="spacer"></span>{crit_line}</div>
  <div class="card-b scroll-x">{graph or '<div class="empty">No graph recorded for this run.</div>'}</div>
</section>"""
    timeline = gantt_svg(record)
    timeline_card = f"""
<section class="card" aria-labelledby="h-time">
  <div class="card-h"><h2 id="h-time">Timeline</h2><span class="sub">when each step ran · hatched = retried</span></div>
  <div class="card-b scroll-x">{timeline or '<div class="empty"><b>No timing for this run</b>Step windows are recorded from gauntlet 0.2 onward.</div>'}</div>
</section>"""

    crit_set = set(crit) if len(crit) > 1 else set()
    rows = []
    for r in results:
        href = log_href(r)
        log_cell = f'<a href="{_e(href)}">output.log</a>' if href else '<span class="dim">—</span>'
        window = (
            f"{r.start_s:.2f} → {r.end_s:.2f}s" if r.start_s is not None and r.end_s is not None else "—"
        )
        tags = ""
        if r.flaky:
            tags += ' <span class="tag flaky" title="Passed only after a retry">flaky</span>'
        if r.step_id in crit_set:
            tags += ' <span class="tag crit" title="On the critical path">critical</span>'
        rows.append(
            f'<tr id="step-{_e(r.step_id)}"><td>{_st(r.status.value)}</td>'
            f'<td class="step">{_e(r.step_id)}{tags}</td>'
            f'<td class="num">{r.duration_s:.2f}s</td><td class="num dim">{window}</td>'
            f'<td class="num">{r.attempts}</td><td class="num">{len(r.errors)}</td>'
            f'<td class="num">{len(r.warnings)}</td><td class="msg">{_e(_full_detail(r))}</td>'
            f"<td>{log_cell}</td></tr>"
        )
    steps_card = f"""
<section class="card" aria-labelledby="h-steps">
  <div class="card-h"><h2 id="h-steps">Steps</h2><span class="sub">flow order</span></div>
  <div class="card-b flush scroll-x"><table>
    <thead><tr><th>Status</th><th>Step</th><th class="num">Duration</th><th class="num">Window</th><th class="num">Tries</th><th class="num">Err</th><th class="num">Warn</th><th>Detail</th><th>Log</th></tr></thead>
    <tbody>{''.join(rows)}</tbody>
  </table></div>
</section>"""

    return hero + kpis + graph_card + timeline_card + steps_card + _violations_card(
        results, log_href
    ) + _waiver_card(results)


def _full_detail(r: StepResult) -> str:
    """Like the terminal's one-liner, but with room to say all of it."""
    if r.status == StepStatus.FAIL and r.unwaived_errors:
        first = r.unwaived_errors[0]
        more = f" (+{len(r.unwaived_errors) - 1} more)" if len(r.unwaived_errors) > 1 else ""
        return f"[{first.rule_id}] {first.message}{more}"
    if r.status == StepStatus.WAIVED:
        owners = sorted({v.waive_owner for v in r.errors if v.waive_owner})
        by = f" · owner {', '.join(owners)}" if owners else ""
        return f"{_plural(len(r.errors), 'error')} waived{by}"
    return step_detail(r)


def _violations_card(results: list[StepResult], log_href: LogHref) -> str:
    rows = []
    n_err = n_unwaived = n_waived = n_warn = 0
    for r in results:
        href = log_href(r)
        for v in r.violations:
            n_err += v.severity == "ERROR"
            n_unwaived += v.severity == "ERROR" and not v.waived
            n_waived += v.waived
            n_warn += v.severity == "WARNING"
            line = f'<a href="{_e(href)}#L{v.line_no}">{v.line_no}</a>' if href else str(v.line_no)
            waiver = ""
            if v.waived:
                owner = f" · {_e(v.waive_owner)}" if v.waive_owner else ""
                waiver = f'<span class="tag" title="{_e(v.waive_reason or "")}">waived{owner}</span>'
            rows.append(
                f'<tr data-sev="{_e(v.severity)}" data-waived="{int(v.waived)}"'
                f'{" class=waived-row" if v.waived else ""}>'
                f'<td class="step">{_e(r.step_id)}</td><td class="mono">{_e(v.rule_id)}</td>'
                f'<td><span class="sev {_e(v.severity)}">{_e(v.severity)}</span></td>'
                f'<td class="num">{line}</td><td class="msg">{_e(v.message)}'
                + (f'<div class="dim" style="font-size:12px">waived: {_e(v.waive_reason)}</div>' if v.waive_reason else "")
                + f"</td><td>{waiver}</td></tr>"
            )
    if not rows:
        return """
<section class="card"><div class="card-h"><h2>Violations</h2></div>
  <div class="empty"><b>Clean logs</b>No rule in any rulepack matched a single line.</div></section>"""
    total = len(rows)
    return f"""
<section class="card" aria-labelledby="h-viol">
  <div class="card-h"><h2 id="h-viol">Violations</h2><span class="sub" id="vcount">{total} shown</span>
    <div class="filters" role="group" aria-label="Filter violations">
      <button class="chip" type="button" data-filter="all" aria-pressed="true">All<span class="c">{total}</span></button>
      <button class="chip" type="button" data-filter="unwaived" aria-pressed="false">Unwaived errors<span class="c">{n_unwaived}</span></button>
      <button class="chip" type="button" data-filter="waived" aria-pressed="false">Waived<span class="c">{n_waived}</span></button>
      <button class="chip" type="button" data-filter="warning" aria-pressed="false">Warnings<span class="c">{n_warn}</span></button>
      <input class="search" id="vsearch" type="search" placeholder="filter by text…" aria-label="Filter violations by text">
    </div>
  </div>
  <div class="card-b flush scroll-x"><table id="violations">
    <thead><tr><th>Step</th><th>Rule</th><th>Severity</th><th class="num">Line</th><th>Message</th><th>Waiver</th></tr></thead>
    <tbody>{''.join(rows)}</tbody>
  </table></div>
</section>"""


def _waiver_card(results: list[StepResult]) -> str:
    waived = [(r.step_id, v) for r in results for v in r.violations if v.waived]
    if not waived:
        return ""
    items = "".join(
        f"<tr><td class=\"step\">{_e(sid)}</td><td class=\"mono\">{_e(v.rule_id)}</td>"
        f"<td>{_e(v.waive_owner or '—')}</td><td class=\"msg\">{_e(v.waive_reason or '—')}</td></tr>"
        for sid, v in waived
    )
    return f"""
<section class="card" aria-labelledby="h-waive">
  <div class="card-h"><h2 id="h-waive">Waiver debt</h2><span class="sub">a waiver is a debt, not a fix — every one has an owner</span></div>
  <div class="card-b flush scroll-x"><table>
    <thead><tr><th>Step</th><th>Rule</th><th>Owner</th><th>Reason</th></tr></thead>
    <tbody>{items}</tbody>
  </table></div>
</section>"""


# ───────────────────────────────────────────────────────────────── diff


def diff_body(diff: RunDiff, a: RunRecord, b: RunRecord, run_href: Callable[[str], str]) -> str:
    regress = bool(diff.new_failures)
    verdict = "REGRESSION" if regress else ("IMPROVED" if diff.fixed and not diff.still_failing else "NO REGRESSION")
    cls = "FAIL" if regress else "PASS"
    icon = ICON_X if regress else ICON_CHECK
    hero = f"""
<section class="card hero v-{cls}">
  <div class="hero-top">
    <div style="min-width:0"><div class="eyebrow">Run-to-run diff · flow {_e(diff.flow_name)}</div>
    <h1>{_e(diff.verdict_line())}</h1></div>
    <div class="verdict {cls}" role="status">{icon}{_e(verdict)}</div>
  </div>
  <div class="meta">
    <span>baseline <a href="{_e(run_href(a.run_id))}"><b>{_e(a.run_id)}</b></a> {_st(a.status)}</span>
    <span class="arrow">→</span>
    <span>candidate <a href="{_e(run_href(b.run_id))}"><b>{_e(b.run_id)}</b></a> {_st(b.status)}</span>
    <span>exit code <b>{1 if regress else 0}</b>{' → CI gate trips' if regress else ''}</span>
  </div>
</section>"""

    def bucket(kind: str, label: str, items: list[str]) -> str:
        lis = "".join(f"<li>{_e(s)}</li>" for s in items) or '<li class="dim">none</li>'
        return f'<div class="bucket {kind}"><div class="l">{label}</div><div class="n">{len(items)}</div><ul>{lis}</ul></div>'

    buckets = (
        '<section class="card card-b"><div class="buckets">'
        + bucket("new", "New failures", [r.step_id for r in diff.new_failures])
        + bucket("fixed", "Fixed", [r.step_id for r in diff.fixed])
        + bucket("still", "Still failing", [r.step_id for r in diff.still_failing])
        + bucket("same", "Unchanged pass", [r.step_id for r in diff.unchanged_pass])
        + (bucket("same", "New steps", diff.new_steps) if diff.new_steps else "")
        + (bucket("same", "Removed steps", diff.removed_steps) if diff.removed_steps else "")
        + "</div></section>"
    )

    change_of: dict[str, tuple[str, str]] = {}
    for r in diff.new_failures:
        change_of[r.step_id] = ("new", "NEW FAILURE")
    for r in diff.fixed:
        change_of[r.step_id] = ("fixed", "FIXED")
    for r in diff.still_failing:
        change_of[r.step_id] = ("still", "STILL FAILING")
    for sid in diff.new_steps:
        change_of[sid] = ("same", "NEW STEP")
    for sid in diff.removed_steps:
        change_of[sid] = ("same", "REMOVED")

    order = list(b.dag or b.results) + [s for s in (a.dag or a.results) if s not in b.results]
    rows = []
    for sid in order:
        ra, rb = a.results.get(sid), b.results.get(sid)
        kind, label = change_of.get(sid, ("same", "same"))
        if label == "same" and ra and rb and ra.status != rb.status:
            label = f"{ra.status.value.lower()} → {rb.status.value.lower()}"
        detail = _full_detail(rb) if rb else "not in candidate run"
        rows.append(
            f'<tr><td class="step">{_e(sid)}</td>'
            f'<td>{_st(ra.status.value) if ra else _st("NONE")}</td><td class="arrow">→</td>'
            f'<td>{_st(rb.status.value) if rb else _st("NONE")}</td>'
            f'<td><span class="change {kind}">{_e(label)}</span></td>'
            f'<td class="msg">{_e(detail)}</td></tr>'
        )
    table = f"""
<section class="card"><div class="card-h"><h2>Step by step</h2><span class="sub">SKIPPED is not a failure — the diff blames the step that actually broke</span></div>
  <div class="card-b flush scroll-x"><table>
    <thead><tr><th>Step</th><th>Baseline</th><th></th><th>Candidate</th><th>Change</th><th>Candidate detail</th></tr></thead>
    <tbody>{''.join(rows)}</tbody></table></div></section>"""
    return hero + buckets + table


# ────────────────────────────────────────────────────────────── runs list


def runs_body(
    rows: list[dict],
    flows: list[str],
    active_flow: str | None,
    run_href: Callable[[str], str],
) -> str:
    if not rows:
        return """
<section class="card"><div class="empty" style="padding:64px 18px"><b>No runs yet</b>
Run a flow and it shows up here on its own:<br><br><code>gauntlet run flows/smoke.yaml</code></div></section>"""

    passed = sum(1 for r in rows if r["status"] == "PASS")
    durations = sorted(_row_duration(r) for r in rows)
    median = durations[len(durations) // 2]
    latest = rows[0]
    streak = 0
    for r in rows:
        if r["status"] != latest["status"]:
            break
        streak += 1

    chips = "".join(
        f'<a class="chip" href="/?flow={_e(quote(f))}" aria-pressed="{str(f == active_flow).lower()}">{_e(f)}</a>'
        for f in flows
    )
    if len(flows) > 1:
        chips = f'<a class="chip" href="/" aria-pressed="{str(active_flow is None).lower()}">all flows</a>' + chips

    kpis = f"""
<section class="card card-b"><div class="kpis">
  <div class="kpi {'good' if latest['status'] == 'PASS' else 'bad'}"><div class="l">Latest</div><div class="n">{_e(latest['status'])}</div><div class="d">{_e(latest['run_id'])}</div></div>
  <div class="kpi"><div class="l">Pass rate</div><div class="n">{100 * passed / len(rows):.0f}<small>%</small></div><div class="d">{passed} of last {len(rows)} runs</div></div>
  <div class="kpi"><div class="l">Streak</div><div class="n">{streak}</div><div class="d">{_e(latest['status'].lower())} in a row</div></div>
  <div class="kpi"><div class="l">Median run</div><div class="n">{median:.1f}<small>s</small></div><div class="d">wall clock</div></div>
  <div class="kpi"><div class="l">Flows</div><div class="n">{len(flows)}</div><div class="d">with recorded runs</div></div>
</div></section>"""

    trend = f"""
<section class="card"><div class="card-h"><h2>Trend</h2><span class="sub">bar height = duration · color = verdict · click to open</span>
  <div class="filters">{chips}</div></div>
  <div class="card-b scroll-x">{trend_svg(rows, run_href)}</div></section>"""

    options = "".join(
        f'<option value="{_e(r["run_id"])}">{_e(r["run_id"])} · {_e(r["status"])}</option>' for r in rows
    )
    compare = f"""
<section class="card"><div class="card-h"><h2>Compare two runs</h2><span class="sub">what broke that was working?</span></div>
  <form class="card-b" action="/diff" method="get" style="display:flex;gap:10px;flex-wrap:wrap;align-items:center">
    <label class="dim mono" for="a">baseline</label><select class="search" id="a" name="a">{options}</select>
    <label class="dim mono" for="b">candidate</label><select class="search" id="b" name="b">{options}</select>
    <button class="btn" type="submit">Diff</button>
  </form></section>"""

    body_rows = []
    for i, r in enumerate(rows):
        dur = _row_duration(r)
        prev = rows[i + 1]["run_id"] if i + 1 < len(rows) else None
        diff_link = (
            f'<a href="/diff?a={_e(quote(prev))}&amp;b={_e(quote(r["run_id"]))}">vs previous</a>' if prev else '<span class="dim">—</span>'
        )
        commit = _e((r.get("git_commit") or "")[:8]) or '<span class="dim">—</span>'
        fail_cls = "num" + ("" if r["failed_steps"] else " dim")
        body_rows.append(
            f'<tr><td>{_st(r["status"])}</td><td class="step"><a href="{_e(run_href(r["run_id"]))}">{_e(r["run_id"])}</a></td>'
            f'<td class="mono">{_e(r["flow_name"])}</td><td class="dim mono">{_e(r["started_at"].replace("T", " "))}</td>'
            f'<td class="num">{dur:.1f}s</td><td class="{fail_cls}">{r["failed_steps"]}/{r.get("total_steps", "?")}</td>'
            f'<td class="mono">{commit}</td><td>{diff_link}</td></tr>'
        )
    table = f"""
<section class="card"><div class="card-h"><h2>Runs</h2><span class="sub">newest first</span></div>
  <div class="card-b flush scroll-x"><table class="nowrap">
  <thead><tr><th>Status</th><th>Run</th><th>Flow</th><th>Started</th><th class="num">Duration</th><th class="num">Failing</th><th>Commit</th><th>Diff</th></tr></thead>
  <tbody>{''.join(body_rows)}</tbody></table></div></section>"""

    # Preselect "previous vs latest" so one click answers the usual question.
    preselect = ""
    if len(rows) > 1:
        preselect = (
            f"document.getElementById('a').value={json.dumps(rows[1]['run_id'])};"
            f"document.getElementById('b').value={json.dumps(rows[0]['run_id'])};"
        )
    return kpis + trend + compare + table + f"<script>{preselect}</script>"


# ─────────────────────────────────────────────────────────────── stats


def stats_body(flow_name: str, n_runs: int, stats: list[StepStats], flows: list[str]) -> str:
    if not stats:
        return '<section class="card"><div class="empty"><b>No history yet</b>Run a flow a few times first.</div></section>'
    chips = "".join(
        f'<a class="chip" href="/stats?flow={_e(quote(f))}" aria-pressed="{str(f == flow_name).lower()}">{_e(f)}</a>'
        for f in flows
    )
    rows = []
    for s in stats:
        cells = "".join(
            f'<i class="{"none" if st is None else "bg-" + st.value}" title="{_e(st.value if st else "absent")}"></i>'
            for st in s.statuses
        )
        rate = s.pass_rate
        rate_html = (
            '<span class="dim">—</span>'
            if rate is None
            else f'<span class="rate"><span class="track"><span class="fill {"" if rate >= 0.9 else ("mid" if rate >= 0.6 else "low")}" style="width:{100 * rate:.0f}%"></span></span>{100 * rate:.0f}%</span>'
        )
        verdict_cls = "never" if s.verdict == "never ran" else s.verdict
        mean = "—" if s.mean_duration is None else f"{s.mean_duration:.2f}s"
        p95 = "—" if s.p95_duration is None else f"{s.p95_duration:.2f}s"
        rows.append(
            f'<tr><td class="step">{_e(s.step_id)}</td><td><span class="strip">{cells}</span></td>'
            f"<td>{rate_html}</td><td class=\"num\">{s.flips}</td><td class=\"num\">{s.flaky}</td>"
            f'<td class="num">{mean}</td><td class="num">{p95}</td>'
            f'<td><span class="verdict-tag {verdict_cls}">{_e(s.verdict)}</span></td></tr>'
        )
    noisy = [s.step_id for s in stats if s.verdict in ("flaky", "failing")]
    callout = (
        f'<span class="tag flaky">needs an owner: {_e(", ".join(noisy))}</span>' if noisy else '<span class="tag">all quiet</span>'
    )
    return f"""
<section class="card hero"><div class="hero-top"><div><div class="eyebrow">Step stability · last {n_runs} runs</div>
  <h1>{_e(flow_name)}</h1></div></div>
  <div class="meta"><span>A diff says what changed between two runs. This says which steps keep changing — noise is where real regressions hide.</span></div>
  <div class="filters" style="margin-left:0">{chips}</div></section>
<section class="card"><div class="card-h"><h2>Steps</h2><span class="sub">history reads oldest → newest</span><span class="spacer"></span>{callout}</div>
  <div class="card-b flush scroll-x"><table>
  <thead><tr><th>Step</th><th>History</th><th>Pass rate</th><th class="num">Flips</th><th class="num">Flaky</th><th class="num">Mean</th><th class="num">P95</th><th>Verdict</th></tr></thead>
  <tbody>{''.join(rows)}</tbody></table></div></section>"""


# ─────────────────────────────────────────────────────────────── log view


def log_body(record: RunRecord, result: StepResult, lines: list[str], truncated: bool, run_href: str) -> str:
    hits: dict[int, str] = {}
    for v in result.violations:
        hits[v.line_no] = "waived" if v.waived else v.severity
    out = []
    for i, text in enumerate(lines, start=1):
        cls = f" hit-{hits[i]}" if i in hits else ""
        out.append(
            f'<div class="ln{cls}" id="L{i}"><a class="no" href="#L{i}">{i}</a><code>{_e(text.rstrip(chr(10)))}</code></div>'
        )
    note = (
        f'<div class="empty">Showing the first {len(lines)} lines — the log continues on disk.</div>' if truncated else ""
    )
    return f"""
<section class="card hero v-{'PASS' if result.status.value in ('PASS', 'WAIVED') else 'FAIL'}">
  <div class="hero-top"><div style="min-width:0"><div class="eyebrow">Log · {_e(record.flow_name)}</div>
  <h1>{_e(result.step_id)}</h1></div><div class="verdict" style="padding:0">{_st(result.status.value)}</div></div>
  <div class="meta"><span>run <a href="{_e(run_href)}"><b>{_e(record.run_id)}</b></a></span>
  <span>{_plural(len(result.violations), 'violation')} highlighted</span><span class="dim">{_e(result.log_path)}</span></div>
</section>
<section class="card"><div class="card-b flush log">{''.join(out) or '<div class="empty">empty log</div>'}</div>{note}</section>"""


